/**
 * Format key-value pairs into a clean HTML table
 */
function renderDetailsTable(details) {
  const rows = details
    .filter((d) => d.value !== undefined && d.value !== null && d.value !== "")
    .map(
      (d) => `
      <tr>
        <td style="padding: 11px 14px; border-bottom: 1px solid #EAECE2; color: #5C6051; font-size: 14px; font-weight: 600; width: 34%; vertical-align: top;">
          ${escapeHtml(d.label)}
        </td>
        <td style="padding: 11px 14px; border-bottom: 1px solid #EAECE2; color: #1F2922; font-size: 14px; vertical-align: top;">
          ${
            d.isLink && d.href
              ? `<a href="${d.href}" style="color: #2F6914; text-decoration: none; font-weight: 600;">${escapeHtml(
                  d.value
                )}</a>`
              : escapeHtml(d.value)
          }
        </td>
      </tr>
    `
    )
    .join("");

  return `
    <table width="100%" border="0" cellpadding="0" cellspacing="0" style="border: 1px solid #E5E8D8; border-radius: 12px; overflow: hidden; margin-top: 16px; margin-bottom: 20px; background-color: #FAFBF7;">
      ${rows}
    </table>
  `;
}

