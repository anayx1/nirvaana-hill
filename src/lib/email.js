import nodemailer from "nodemailer";

/**
 * Escapes HTML special characters to prevent HTML injection in emails.
 */
function escapeHtml(str) {
  if (!str) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/**
 * Create and configure the Nodemailer SMTP transporter.
 */
function getTransporter() {
  const host = process.env.SMTP_HOST || "smtp.gmail.com";
  const port = parseInt(process.env.SMTP_PORT || "465", 10);
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;
  const secure = process.env.SMTP_SECURE === "true" || port === 465;

  if (!user || !pass) {
    return null;
  }

  return nodemailer.createTransport({
    host,
    port,
    secure,
    auth: {
      user,
      pass,
    },
    tls: {
      rejectUnauthorized: false,
    },
  });
}

/**
 * Generic email sender.
 */
export async function sendMail({ to, subject, html, text, replyTo }) {
  const transporter = getTransporter();
  const fromAddress =
    process.env.SMTP_FROM ||
    `"Nirvaana Hills" <${process.env.SMTP_USER || "no-reply@nirvaanahills.com"}>`;

  if (!transporter) {
    console.warn(
      "⚠️ SMTP is not configured yet. Set SMTP_USER and SMTP_PASS in .env.local to send live emails."
    );
    console.log(`[Mock Email to ${to}] Subject: ${subject}`);
    return { success: false, reason: "SMTP_NOT_CONFIGURED" };
  }

  try {
    const info = await transporter.sendMail({
      from: fromAddress,
      to,
      replyTo: replyTo || undefined,
      subject,
      text,
      html,
    });
    console.log("✅ Email sent successfully:", info.messageId);
    return { success: true, messageId: info.messageId };
  } catch (error) {
    console.error("❌ Failed to send email via SMTP:", error);
    return { success: false, error: error.message };
  }
}

